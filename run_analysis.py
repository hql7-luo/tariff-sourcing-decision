"""Run the full analysis: tables in results/, charts in figures/, data for the web explorer.

Usage:  python run_analysis.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "src"))

from sourcing import charts  # noqa: E402
from sourcing.analysis import (cost_breakdown, decision_boundaries, scenario_table,  # noqa: E402
                               sensitivity, thresholds)
from sourcing.inputs import build_sites, load_inputs, load_scenarios  # noqa: E402
from sourcing.simulate import UNCERTAIN_INPUTS, run_monte_carlo, summarize  # noqa: E402

RESULTS = ROOT / "results"
FIGURES = ROOT / "figures"
EXPLORER_DATA = ROOT / "docs" / "model-data.js"
RECOMMENDED = "staged"


def main():
    RESULTS.mkdir(exist_ok=True)
    FIGURES.mkdir(exist_ok=True)

    inp = load_inputs()
    scenarios = load_scenarios()
    today = next(s for s in scenarios if s["name"] == "status_quo")["tariff"]

    # 1) Cost breakdown at today's tariffs
    breakdown = cost_breakdown(inp, today)
    breakdown.round(2).to_csv(RESULTS / "cost_breakdown.csv", index=False)

    # 2) Every strategy under every tariff scenario
    by_scenario, expected = scenario_table(inp, scenarios)
    by_scenario.round(3).to_csv(RESULTS / "scenario_results.csv", index=False)
    expected.round(2).to_csv(RESULTS / "scenario_expected.csv", index=False)

    # 3) Thresholds and sensitivity
    limits = thresholds(inp, scenarios)
    limits.round(4).to_csv(RESULTS / "thresholds.csv", index=False)
    sens = sensitivity(inp, scenarios)
    sens.round(2).to_csv(RESULTS / "sensitivity.csv", index=False)

    # 4) Monte Carlo
    simulation = run_monte_carlo(inp, scenarios, n_draws=10000, seed=2026)
    summary = summarize(simulation)
    summary.round(3).to_csv(RESULTS / "simulation_summary.csv", index=False)
    site_wins = (simulation[["china", "vietnam", "mexico"]].idxmin(axis=1)
                 .value_counts(normalize=True).rename("share").rename_axis("site").reset_index())
    site_wins.round(4).to_csv(RESULTS / "simulation_cheapest_site.csv", index=False)

    # 5) Decision map boundaries
    boundaries = decision_boundaries(inp)

    # 6) Charts
    charts.use_style()
    charts.plot_cost_components(breakdown, FIGURES / "1_cost_components.png")
    charts.plot_decision_map(boundaries, scenarios, FIGURES / "2_decision_map.png")
    charts.plot_strategies(summary, RECOMMENDED, FIGURES / "3_strategies_under_uncertainty.png")
    charts.plot_sensitivity(sens, FIGURES / "4_what_changes_the_answer.png")

    # 7) Inputs for the web explorer (same numbers, computed in the browser)
    export = {
        "inputs": inp,
        "sites": build_sites(inp),
        "scenarios": scenarios,
        "uncertain_inputs": UNCERTAIN_INPUTS,
        "boundaries": boundaries,
        "check_values": {
            "status_quo_avg_cost_per_k": {
                row["option"]: row["avg_cost_per_k"]
                for _, row in by_scenario[by_scenario["scenario"] == "status_quo"].iterrows()
            },
        },
    }
    EXPLORER_DATA.write_text(
        "// Generated by run_analysis.py. Do not edit by hand.\n"
        "var MODEL_DATA = " + json.dumps(export, indent=1) + ";\n"
        "if (typeof module !== 'undefined') module.exports = MODEL_DATA;\n"
    )

    # Console summary
    print("\nAverage landed cost per 1,000 cartons over 5 years, by tariff scenario:")
    print(by_scenario.pivot(index="label", columns="scenario_label", values="avg_cost_per_k")
          .round(1).to_string())
    print("\nProbability-weighted:")
    print(expected[["label", "avg_cost_per_k"]].round(1).to_string(index=False))
    print("\nThresholds:")
    print(limits.round(3).to_string(index=False))
    print("\nSimulation (10,000 draws):")
    print(summary.round(2).to_string(index=False))
    print("\nCheapest site in hindsight:")
    print(site_wins.round(3).to_string(index=False))
    print(f"\nWrote tables to {RESULTS.name}/, charts to {FIGURES.name}/, explorer data to docs/model-data.js")


if __name__ == "__main__":
    main()
